"""Stamps when the prototype last changed into lib/last_update.g.dart.

The header shows it as "Last update <Mon YYYY>". It must say when the
prototype changed, never today's date: a prototype nobody touched in three
months has to look three months old.

- Inside a git repo (the real prototypes, in aura_ds): the date of the last
  commit that touched this folder. If the folder has uncommitted changes,
  the newest of those files' dates instead. File dates alone are not used for
  committed work, because a fresh clone in CI stamps every file with the
  clone's date.
- Outside git (this sandbox): the newest source file's date.

Writes only when the month changes, so a file watcher does not loop.
Run before every build:  python3 tool/stamp_last_update.py

Inside a bigger repo, where the prototype is a few files among many, name
them and where to write:

  python3 stamp_last_update.py --out lib/ai_coach/last_update.g.dart \
      lib/ai_coach lib/ai_coach_plays.dart
"""
import datetime
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIB = os.path.join(ROOT, "lib")
OUT = os.path.join(LIB, "last_update.g.dart")
SOURCES = [LIB]

# --out <file> [paths...]: paths are relative to the current directory.
args = sys.argv[1:]
if "--out" in args:
    i = args.index("--out")
    OUT = os.path.abspath(args[i + 1])
    rest = args[:i] + args[i + 2:]
    if rest:
        SOURCES = [os.path.abspath(a) for a in rest]
    ROOT = os.path.dirname(OUT)


def source_files():
    for src in SOURCES:
        if os.path.isfile(src):
            yield src
            continue
        for d, _, files in os.walk(src):
            for f in files:
                yield os.path.join(d, f)


def newest_source_date():
    newest = 0.0
    for p in source_files():
        if p.endswith(".dart") and p != OUT:
            newest = max(newest, os.path.getmtime(p))
    return datetime.datetime.fromtimestamp(newest)


def git(*args):
    return subprocess.run(
        ["git", "-C", ROOT, *args], capture_output=True, text=True
    ).stdout.strip()


def changed_date():
    if git("rev-parse", "--is-inside-work-tree") == "true":
        dirty = git("status", "--porcelain", "--", *SOURCES)
        dirty = [l for l in dirty.splitlines() if not l.endswith("last_update.g.dart")]
        if not dirty:
            stamp = git("log", "-1", "--format=%ct", "--", *SOURCES)
            if stamp:
                return datetime.datetime.fromtimestamp(int(stamp))
    return newest_source_date()


def main():
    # en-US, whatever the machine's locale: "Oct 2026".
    months = "Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec".split()
    d = changed_date()
    label = f"{months[d.month - 1]} {d.year}"
    content = (
        "// Generated by tool/stamp_last_update.py. Do not edit by hand.\n\n"
        "/// When the prototype last changed, as the header shows it.\n"
        f"const String lastUpdate = '{label}';\n"
    )
    old = open(OUT).read() if os.path.exists(OUT) else ""
    if old != content:
        with open(OUT, "w") as f:
            f.write(content)
        print(f"last update → {label}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
